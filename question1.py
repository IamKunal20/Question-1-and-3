def data_distribution(counts):
    distribution = {}

    for key, value in counts.items():
        data_bits = key.split()[-1]
        distribution[data_bits] = (
            distribution.get(data_bits, 0) + value
        )

    total = sum(distribution.values())

    return {
        k: v / total
        for k, v in distribution.items()
    }


