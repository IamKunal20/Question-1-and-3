# Classical measurement-distribution fidelity
def calculate_fidelity(counts1, counts2):

    keys = set(counts1) | set(counts2)

    total1 = sum(counts1.values())
    total2 = sum(counts2.values())

    value = 0

    for key in keys:
        p = counts1.get(key, 0) / total1
        q = counts2.get(key, 0) / total2
        value += np.sqrt(p * q)

    return value ** 2


# Run one experiment
def run_experiment(circuit, postselection, seed):

    result = simulator.run(
        circuit,
        shots=1000,
        seed_simulator=seed
    ).result()

    counts = result.get_counts()

    accepted = {
        bitstring: count
        for bitstring, count in counts.items()
        if np.all(postselection(bitstring) == 0)
    }

    data_counts = marginal_counts(counts, indices=[0, 1, 2])
    accepted_data = marginal_counts(accepted, indices=[0, 1, 2])

    acceptance = sum(accepted.values()) / 1000

    before = calculate_fidelity(
        data_counts,
        true_ideal_data_counts
    )

    after = calculate_fidelity(
        accepted_data,
        true_ideal_data_counts
    )

    return acceptance * 100, before, after


