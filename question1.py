import numpy as np

def calculate_classical_fidelity(counts1, counts2):

    # Use the same measurement outcomes
    all_keys = set(counts1.keys()) | set(counts2.keys())

    total1 = sum(counts1.values())
    total2 = sum(counts2.values())

    fidelity_sum = 0

    for key in all_keys:
        p = counts1.get(key, 0) / total1
        q = counts2.get(key, 0) / total2

        fidelity_sum += np.sqrt(p * q)

    return fidelity_sum ** 2


