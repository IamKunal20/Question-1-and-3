# Check the rank of the stabilizer generators
def binary_rank(matrix):
    matrix = np.array(matrix, dtype=np.uint8).copy()
    rows, cols = matrix.shape
    rank = 0

    for col in range(cols):
        pivot = next(
            (r for r in range(rank, rows) if matrix[r, col]),
            None
        )

        if pivot is None:
            continue

        matrix[[rank, pivot]] = matrix[[pivot, rank]]

        for r in range(rows):
            if r != rank and matrix[r, col]:
                matrix[r] ^= matrix[rank]

        rank += 1

    return rank


