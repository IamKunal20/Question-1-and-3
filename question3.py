def commutes_with_checks(operator, checks):
    return all(
        sum(operator[q] for q in check) % 2 == 0
        for check in checks
    )

def is_in_stabilizer(operator, checks):
    for mask in range(1 << len(checks)):
        combined = np.zeros(9, dtype=int)

        for i, check in enumerate(checks):
            if (mask >> i) & 1:
                combined[check] ^= 1

        if np.array_equal(combined, operator):
            return True

    return False

def find_logical_operator(commuting_checks, stabilizer_checks):
    candidates = []

    for mask in range(1, 1 << 9):
        operator = np.array(
            [(mask >> q) & 1 for q in range(9)]
        )

        if (commutes_with_checks(operator, commuting_checks)
                and not is_in_stabilizer(operator, stabilizer_checks)):
            candidates.append(operator)

    candidates.sort(key=lambda op: np.sum(op))
    return candidates[0]

