def exact_decoder_fidelity(px, pz):

    probabilities = np.array([
        (1-px)*(1-pz),
        px*(1-pz),
        (1-px)*pz,
        px*pz
    ])

    data = {}

    for error_tuple in product(range(4), repeat=N):
        error = np.array(error_tuple)

        prob = np.prod(probabilities[list(error)])
        syndrome = calculate_syndrome(error)
        sector = logical_sector(error)

        if syndrome not in data:
            data[syndrome] = np.zeros(4)

        data[syndrome][sector] += prob

    return (
        sum(np.max(v) for v in data.values())
        / sum(np.sum(v) for v in data.values())
    )

