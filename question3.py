def build_syndrome_tensor(target_syndrome, probabilities):
    tensor = np.zeros((4,) * N)

    for error_tuple in product(range(4), repeat=N):
        error = np.array(error_tuple)

        if calculate_syndrome(error) == target_syndrome:
            tensor[error_tuple] = np.prod(
                probabilities[list(error)]
            )

    return tensor

def tt_svd(tensor, max_bond=32, cutoff=1e-8):

    shape = tensor.shape
    cores = []
    current = tensor.copy()
    rank = 1
    discarded_weight = 0.0
    retained_bonds = []

    for n in range(len(shape)-1):

        current = current.reshape(
            rank*shape[n], -1
        )

        U, S, Vh = np.linalg.svd(
            current, full_matrices=False
        )

        threshold = cutoff * S[0] if len(S) else 0

        keep = max(1, int(np.sum(S > threshold)))
        keep = min(keep, max_bond)

        discarded_weight += np.sum(S[keep:]**2)

        U = U[:, :keep]
        S = S[:keep]
        Vh = Vh[:keep, :]

        cores.append(U.reshape(rank, shape[n], keep))

        current = np.diag(S) @ Vh
        rank = keep
        retained_bonds.append(keep)

    cores.append(current.reshape(rank, shape[-1], 1))

    return cores, discarded_weight, retained_bonds

def reconstruct_tt(cores):
    result = cores[0]

    for core in cores[1:]:
        result = np.tensordot(
            result, core, axes=([-1], [0])
        )

    return np.squeeze(result, axis=(0, -1))

syndrome_tensor = build_syndrome_tensor(
    selected_syndrome,
    pauli_probabilities
)

thresholds = [1e-2, 1e-4, 1e-6, 1e-8]
bond_dimensions = [2, 4, 8, 16, 32]

truncation_results = []
bond_results = []

for cutoff in thresholds:

    cores, discarded, bonds = tt_svd(
        syndrome_tensor, 32, cutoff
    )

    reconstructed = reconstruct_tt(cores)

    relative_error = (
        np.linalg.norm(syndrome_tensor-reconstructed)
        / max(np.linalg.norm(syndrome_tensor), 1e-15)
    )

    truncation_results.append(
        (cutoff, relative_error, discarded)
    )

for bond in bond_dimensions:

    cores, discarded, bonds = tt_svd(
        syndrome_tensor, bond, 1e-8
    )

    reconstructed = reconstruct_tt(cores)

    relative_error = (
        np.linalg.norm(syndrome_tensor-reconstructed)
        / max(np.linalg.norm(syndrome_tensor), 1e-15)
    )

    bond_results.append((bond, relative_error))

