def stabilizer_product(operator, checks):
    for mask in range(1 << len(checks)):
        combined = np.zeros(N, dtype=int)

        for i, check in enumerate(checks):
            if (mask >> i) & 1:
                combined[check] ^= 1

        if np.array_equal(combined, operator):
            return True

    return False

def erasure_component_success(error, flags, checks, stabilizers):

    positions = np.where(flags == 1)[0]

    actual_syndrome = np.array([
        sum(error[q] for q in check) % 2
        for check in checks
    ])

    candidates = []

    for mask in range(1 << len(positions)):

        correction = np.zeros(N, dtype=int)

        for i, q in enumerate(positions):
            correction[q] = (mask >> i) & 1

        candidate_syndrome = np.array([
            sum(correction[q] for q in check) % 2
            for check in checks
        ])

        if np.array_equal(candidate_syndrome, actual_syndrome):

            residual = (error + correction) % 2

            candidates.append(
                stabilizer_product(residual, stabilizers)
            )

    # Optimal logical success: at least one valid
    # correction in the correct logical equivalence class.
    # This routine is a diagnostic baseline, not a
    # maximum-likelihood erasure decoder.
    return any(candidates)

def simulate_erasure(px, pz, trials=2000):

    successes = 0

    for _ in range(trials):

        x_flags = (
            np.random.random(N) < px
        ).astype(int)

        z_flags = (
            np.random.random(N) < pz
        ).astype(int)

        x_error = (
            np.random.randint(0, 2, N) * x_flags
        )

        z_error = (
            np.random.randint(0, 2, N) * z_flags
        )

        x_ok = erasure_component_success(
            x_error, x_flags, Z, x_checks
        )

        z_ok = erasure_component_success(
            z_error, z_flags, X, z_checks
        )

        if x_ok and z_ok:
            successes += 1

    return successes / trials

