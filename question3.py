def is_stabilizer_product(operator, checks):

    for mask in range(1 << len(checks)):
        combined = np.zeros(num_data_qubits, dtype=int)

        for i, check in enumerate(checks):
            if (mask >> i) & 1:
                combined[check] ^= 1

        if np.array_equal(combined, operator):
            return True

    return False


def calculate_logical_distance(commuting_checks, stabilizer_checks):

    minimum_weight = num_data_qubits + 1
    best_operator = None

    for mask in range(1, 1 << num_data_qubits):

        operator = np.array([
            (mask >> q) & 1
            for q in range(num_data_qubits)
        ])

        # Must commute with opposite-type stabilizers
        if not all(
            np.sum(operator[check]) % 2 == 0
            for check in commuting_checks
        ):
            continue

        # Must not be a stabilizer product
        if is_stabilizer_product(operator, stabilizer_checks):
            continue

        weight = int(np.sum(operator))

        if weight < minimum_weight:
            minimum_weight = weight
            best_operator = operator.copy()

    return minimum_weight, best_operator


