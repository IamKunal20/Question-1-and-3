# STEP 19: TENSOR TRAIN SVD WITH DYNAMIC TRUNCATION

def tt_svd(tensor, max_bond=16, cutoff=1e-8):

    shape = tensor.shape
    cores = []
    current = tensor.copy()
    rank = 1
    discarded_weight = 0.0

    for n in range(len(shape) - 1):

        current = current.reshape(rank * shape[n], -1)

        U, S, Vh = np.linalg.svd(current, full_matrices=False)

        # Keep singular values above the truncation threshold
        if len(S) > 0:
            threshold = cutoff * S[0]
            keep = max(1, int(np.sum(S > threshold)))
        else:
            keep = 1

        keep = min(keep, max_bond)

        discarded_weight += np.sum(S[keep:] ** 2)

        U = U[:, :keep]
        S = S[:keep]
        Vh = Vh[:keep, :]

        cores.append(U.reshape(rank, shape[n], keep))

        current = np.diag(S) @ Vh
        rank = keep

    cores.append(current.reshape(rank, shape[-1], 1))

    return cores, discarded_weight


