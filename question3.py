# Each data qubit is a dimension-4 variable.
# Check factors enforce the measured syndrome.
# XOR-chain factors accumulate the two logical parities.

def make_check_factor(check, target, component):
    shape = (4,) * len(check)
    factor = np.zeros(shape)

    for states in product(range(4), repeat=len(check)):
        if component == "z":
            parity = sum(states) % 2
        else:
            parity = sum(s // 2 for s in states) % 2

        if parity == target:
            factor[states] = 1.0

    return factor

def make_xor_factor(bit_type):
    # Inputs: Pauli state, previous parity, next parity.
    # bit_type = 0: extract X component
    # bit_type = 1: extract Z component
    factor = np.zeros((4, 2, 2))

    for state in range(4):
        bit = state % 2 if bit_type == 0 else state // 2

        for previous in range(2):
            following = previous ^ bit
            factor[state, previous, following] = 1.0

    return factor

def contract_four_sectors(target_syndrome, probabilities):

    operands = []
    next_index = 0
    qubit_indices = list(range(N))
    next_index = N

    # Local single-qubit probability tensors
    for q in range(N):
        operands.extend([
            probabilities,
            [qubit_indices[q]]
        ])

    # X-check syndrome factors detect Z errors
    for i, check in enumerate(x_checks):
        factor = make_check_factor(
            check, target_syndrome[i], "x"
        )
        operands.extend([
            factor,
            check
        ])

    # Z-check syndrome factors detect X errors
    for i, check in enumerate(z_checks):
        factor = make_check_factor(
            check, target_syndrome[4+i], "z"
        )
        operands.extend([
            factor,
            check
        ])

    # Accumulate logical X parity
    for q in range(N):
        previous = next_index
        following = next_index + 1
        next_index += 2

        factor = make_xor_factor(0)

        operands.extend([
            factor,
            [qubit_indices[q], previous, following]
        ])

        if q == 0:
            operands.extend([np.array([1., 0.]), [previous]])

        if q == N-1:
            logical_x_index = following

    # Accumulate logical Z parity
    for q in range(N):
        previous = next_index
        following = next_index + 1
        next_index += 2

        factor = make_xor_factor(1)

        operands.extend([
            factor,
            [qubit_indices[q], previous, following]
        ])

        if q == 0:
            operands.extend([np.array([1., 0.]), [previous]])

        if q == N-1:
            logical_z_index = following

    result = oe.contract(
        *operands,
        [logical_x_index, logical_z_index],
        optimize="auto"
    )

    # Axis 0 = logical X parity
    # Axis 1 = logical Z parity
    # Required order: I, X, Z, XZ
    return np.array([
        result[0, 0],
        result[1, 0],
        result[0, 1],
        result[1, 1]
    ])

